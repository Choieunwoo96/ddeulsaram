-- 업데이트: "방장만 수락/거절 가능" 기능 추가를 위한 마이그레이션
-- Supabase 대시보드 > SQL Editor 에서 이 파일 내용을 그대로 붙여넣고 Run 하세요.
-- (이미 만들어져 있는 rooms 테이블에 컬럼 하나만 추가하는 것이라 기존 데이터는 안전합니다.)

alter table rooms add column if not exists host_token text;

-- 참고: 이 마이그레이션 이전에 만들어진 방들은 host_token이 비어있어서,
-- 그 방들에 대해서는 더 이상 수락/거절 버튼이 아무에게도 보이지 않게 됩니다.
-- (누가 방장인지 서버가 확인할 방법이 없기 때문입니다.) 테스트용으로 만든
-- 방이라면 신경 쓰지 않으셔도 되고, 새로 방을 만들면 정상적으로 방장만
-- 수락/거절할 수 있습니다.
